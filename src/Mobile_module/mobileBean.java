package Mobile_module;

public class mobileBean {
	private int Id;
	private String brand;
	private String model;
	private int battery;
	private String operatingSystemString;

	public int getId() {
		return Id;
	}

	public void setId(int Id) {
		this.Id = Id;
	}

	public String getBrand() {
		return brand;
	}

	public void setBrand(String brand) {
		this.brand = brand;
	}

	public String getModel() {
		return model;
	}

	public void setModel(String model) {
		this.model = model;
	}

	public int getBattery() {
		return battery;
	}

	public void setBattery(int battery) {
		this.battery = battery;
	}

	public String getOperatingSystemString() {
		return operatingSystemString;
	}

	public void setOperatingSystemString(String operatingSystemString) {
		this.operatingSystemString = operatingSystemString;
	}

}
